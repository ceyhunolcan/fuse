"""Feasibility count for the FUSE registered report: do (A, B1, B2) feature triples exist in real histories?

File-level candidate screen, not a bound on the eligible population, run through the
GitHub GraphQL API (read-only, via the authenticated `gh` CLI):
  * repositories: the most-starred Python repositories under MIT, Apache-2.0 or BSD-3-Clause licenses
    that were pushed after the snapshot's lower bound (top N per license);
  * A: a merged, non-bot, feature-like pull request merged on or after the explicit query cutoff that
    changes at least one test file and at least one non-test Python file, with at most 400 changed lines;
  * B: a later merged feature-like pull request with tests, merged within 12 months after A, whose non-test
    Python files intersect A's;
  * triple: A with two such later changes B1, B2; "strict" additionally requires B1 and B2 to share no
    non-test Python file (a proxy for independence).
Porting the reference patches and running their tests (criteria 3-4 of the report) is NOT done here, so these
counts are unvalidated heuristic yields. Truncated records are excluded and recorded.
Raw GraphQL pages and repository search responses are preserved for replay.
The final task cutoff must also respect the exact checkpoint's documented release.
Usage: python3 mining_feasibility.py [per_license=20] [max_pages=6] [cutoff=2026-04-03T00:00:00Z]
Historical version-2/3 counts used 2026-04-01; they are not regenerated by editing this script.
"""
import json, re, subprocess, sys, datetime as dt
from collections import defaultdict
from pathlib import Path

PER_LICENSE = int(sys.argv[1]) if len(sys.argv) > 1 else 20
MAX_PAGES = int(sys.argv[2]) if len(sys.argv) > 2 else 6
CUTOFF = sys.argv[3] if len(sys.argv)>3 else '2026-04-03T00:00:00Z'
SNAPSHOT = Path('mining-query-snapshot')
LICENSES = ['mit', 'apache-2.0', 'bsd-3-clause']
TEST = re.compile(r'(^|/)(tests?|testing)/|(^|/)test_[^/]*\.py$|_test\.py$|(^|/)conftest\.py$')
NONFEATURE = re.compile(r'^\s*(\[[^\]]*\]\s*)?(fix|fixes|fixed|bug|hotfix|docs?|documentation|chore|ci|build|deps?|bump|revert|refactor|style|tests?|typo|release|prepare|update|upgrade|pin|lint|format|cleanup|clean up|remove|deprecate|perf)\b', re.I)
BAD_LABELS = re.compile(r'bug|doc|dependenc|chore|ci|release|refactor|maintenance|test', re.I)
BOT = re.compile(r'bot$|\[bot\]|dependabot|renovate|pre-commit', re.I)

def gh(args):
    out = subprocess.run(['gh', 'api'] + args, capture_output=True, text=True)
    if out.returncode != 0:
        raise RuntimeError(out.stderr[:300])
    return json.loads(out.stdout)

def repos():
    seen, res = set(), []
    for lic in LICENSES:
        q = f'language:python license:{lic} stars:>2000 pushed:>2026-10-01 archived:false'
        r = gh(['-X', 'GET', 'search/repositories', '-f', f'q={q}', '-f', 'sort=stars', '-f', 'order=desc', '-f', f'per_page={PER_LICENSE}'])
        SNAPSHOT.mkdir(exist_ok=True)
        (SNAPSHOT/f'repositories-{lic}.json').write_text(json.dumps(dict(query=q,response=r),indent=2))
        for it in r['items']:
            if it['full_name'] not in seen:
                seen.add(it['full_name']); res.append(dict(repo=it['full_name'], license=lic, stars=it['stargazers_count']))
    return res

QUERY = '''query($owner:String!,$name:String!,$cursor:String){repository(owner:$owner,name:$name){
 pullRequests(states:MERGED,first:50,after:$cursor,orderBy:{field:UPDATED_AT,direction:DESC}){
  pageInfo{hasNextPage endCursor}
  nodes{number title mergedAt additions deletions author{login}
   labels(first:100){pageInfo{hasNextPage} nodes{name}}
   files(first:100){pageInfo{hasNextPage} nodes{path}}}}}}'''

def prs(full):
    owner, name = full.split('/')
    out, cursor = [], None
    for page in range(MAX_PAGES):
        args = ['graphql', '-f', f'query={QUERY}', '-F', f'owner={owner}', '-F', f'name={name}']
        if cursor: args += ['-F', f'cursor={cursor}']
        d = gh(args)['data']['repository']['pullRequests']
        SNAPSHOT.mkdir(exist_ok=True)
        (SNAPSHOT/f"{owner}__{name}__page-{page+1}.json").write_text(json.dumps(d,indent=2))
        nodes = d['nodes']
        out += [n for n in nodes if n['mergedAt'] and n['mergedAt'] >= CUTOFF]
        # UPDATED_AT order does not imply MERGED_AT order. Only stop at exhaustion
        # or the explicit page cap, never at a page of old merge dates.
        if not d['pageInfo']['hasNextPage']:
            break
        cursor = d['pageInfo']['endCursor']
    return out

def classify(p):
    incomplete = (p['files'].get('pageInfo',{}).get('hasNextPage',False) or
                  p['labels'].get('pageInfo',{}).get('hasNextPage',False))
    files = [f['path'] for f in (p['files']['nodes'] or [])]
    tests = [f for f in files if TEST.search(f)]
    src = {f for f in files if f.endswith('.py') and not TEST.search(f)}
    labels = [l['name'] for l in p['labels']['nodes']]
    feature = not NONFEATURE.search(p['title']) and not any(BAD_LABELS.search(l) for l in labels)
    bot = bool(p['author'] and BOT.search(p['author']['login'] or ''))
    return dict(number=p['number'], merged=p['mergedAt'], lines=p['additions'] + p['deletions'], tests=bool(tests),
                src=src, feature=feature and not bot and not incomplete, incomplete=incomplete)

def triples(cls):
    cls = sorted(cls, key=lambda c: c['merged'])
    feat = [c for c in cls if c['feature'] and c['tests'] and c['src']]
    A = [c for c in feat if c['lines'] <= 400]
    out = dict(merged_prs=len(cls), excluded_truncated=sum(c.get('incomplete',False) for c in cls), feature_with_tests=len(feat), A_candidates=len(A), A_with_2B=0, triples=0, triples_strict=0, examples=[], candidate_triples=[])
    for a in A:
        t0 = dt.datetime.fromisoformat(a['merged'].replace('Z', '+00:00'))
        Bs = [b for b in feat if b['merged'] > a['merged'] and b['src'] & a['src'] and
              dt.datetime.fromisoformat(b['merged'].replace('Z', '+00:00')) - t0 <= dt.timedelta(days=365)]
        if len(Bs) >= 2:
            out['A_with_2B'] += 1
            for i in range(len(Bs)):
                for j in range(i + 1, len(Bs)):
                    out['triples'] += 1
                    if not (Bs[i]['src'] & Bs[j]['src']):
                        out['triples_strict'] += 1
                        out['candidate_triples'].append([a['number'],Bs[i]['number'],Bs[j]['number']])
                        if len(out['examples']) < 2:
                            out['examples'].append([a['number'], Bs[i]['number'], Bs[j]['number']])
    return out

if __name__ == '__main__':
    rs = repos()
    rows = []
    for r in rs:
        try:
            c = [classify(p) for p in prs(r['repo'])]
            row = dict(r, **triples(c))
        except Exception as e:
            row = dict(r, error=str(e)[:200])
        rows.append(row)
        print(json.dumps({k: row.get(k) for k in ('repo', 'merged_prs', 'A_candidates', 'A_with_2B', 'triples_strict', 'error') if k in row}), flush=True)
    ok = [r for r in rows if 'error' not in r]
    summary = dict(
        generated=dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds'), cutoff=CUTOFF, repositories_queried=len(rows), repositories_ok=len(ok),
        merged_prs_since_cutoff=sum(r['merged_prs'] for r in ok), A_candidates=sum(r['A_candidates'] for r in ok),
        A_with_two_later_overlapping_features=sum(r['A_with_2B'] for r in ok),
        triples_loose=sum(r['triples'] for r in ok), triples_strict=sum(r['triples_strict'] for r in ok),
        repositories_with_strict_triple=sum(1 for r in ok if r['triples_strict'] > 0),
        note='Unvalidated heuristic candidate yield, not a population upper bound. Top repositories per license with activity/star filters; capped UPDATED_AT pages; truncated PR records excluded. No porting/test validation. Raw inputs saved separately.')
    json.dump(dict(summary=summary, repositories=rows), open('mining_feasibility.json', 'w'), indent=1)
    print(json.dumps(summary, indent=1))
